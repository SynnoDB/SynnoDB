"""Parameterized RTABench: the same queries with their filter values drawn per run.

RTABench ships every query with its values baked in, and a constant query invites a
generated engine to exploit the literals instead of executing - in a CEB run two kernels
compiled down to ``return count_zero()`` because a predicate was provably unsatisfiable.
Under a placeholder there is no constant to fold: the answer has to vary with an argument
the engine only sees at run time.

Two things make a parameterization real rather than decorative, and both are enforced here:

* **Correlated point lookups.** Queries 9, 10 and 11 filter an order id *and* a time window.
  An order's events span about six days while the data covers a year, so drawing the two
  independently returns nothing on ~95% of samples - and an engine returning an empty table
  would pass the correctness sweep. Those ids and days are drawn together, as pairs taken
  from the data.
* **Domains big enough not to memoize.** A parameter with nine values lets an engine
  precompute nine answers at build time and look them up. Every template here has a
  cross-product in the thousands or more.

Nothing of RTABench's SQL is redistributed: each entry is a list of ``(fragment, replacement)``
edits applied to the file in *your* clone, so the query text stays yours and an upstream
change is caught loudly instead of silently ignored.
"""

