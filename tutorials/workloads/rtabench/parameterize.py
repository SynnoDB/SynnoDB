class TemplateDrift(RuntimeError):
    """An edit did not match the upstream query, so the parameterization is out of date."""


def parameterized_queries(only: Any = None) -> Dict[str, dict]:
    """Build the bring-your-own ``queries.json`` entries from your RTABench clone.

    Raises :class:`TemplateDrift` when a fragment is missing from the upstream file - the
    query has changed and its parameterization must be revisited, which is a far better
    outcome than silently generating an engine for a query nobody checked.
    """
    entries: Dict[str, dict] = {}
    for path in _query_files():
        qid = query_id(path)
        recipe = PARAMETERIZATIONS.get(qid)
        if recipe is None or (only is not None and qid not in only):
            continue
        sql = path.read_text().strip().rstrip(";")
        for fragment, replacement in recipe["edits"]:
            if fragment and fragment not in sql:
                raise TemplateDrift(
                    f"Q{qid}: {fragment!r} is not in {path.name}; the upstream query changed "
                    "and this parameterization needs revisiting"
                )
            sql = sql.replace(fragment, replacement) if fragment else sql + replacement
        entry: Dict[str, Any] = {"sql": sql}
        if recipe.get("params"):
            entry["params"] = recipe["params"]
        if recipe.get("param_groups"):
            entry["param_groups"] = recipe["param_groups"]
        entries[qid] = entry
    return entries


def write_parameterized_json(target: Path, only: Any = None) -> Tuple[Path, int]:
    """Write the parameterized catalog; returns the path and how many queries it holds."""
    entries = parameterized_queries(only)
    Path(target).write_text(json.dumps(entries, indent=2))
    return Path(target), len(entries)
